  await assert.rejects(f.manager.deleteSkill(skill.id, skill.revision), code('REVISION_CONFLICT'))
  ;[skill] = await f.manager.listSkills()
  const other = new SkillsManager(f.options)
  const results = await Promise.allSettled([f.manager.setSkillEnabled(skill.id, false, skill.revision), other.setSkillEnabled(skill.id, false, skill.revision)])
