const text = (name = 'sample', extra = '', eol = '\n') => ['---', `name: ${name}`, 'description: A test skill', extra, '---', '# Body', 'Keep **this** exactly.', ''].filter((line, i) => line || i > 4).join(eol)
async function fixture(t: { after: (fn: () => Promise<void>) => void }) {
  const root = await fs.realpath(await fs.mkdtemp(join(tmpdir(), 'skills-engine-')))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const dshHome = join(root, 'dsh'); const agentsHome = join(root, 'agents'); const stateDir = join(root, 'state'); const workspace = join(root, 'workspace')
  await fs.mkdir(workspace)
  const options = { stateDir, dshHome, agentsHome, workspacePaths: () => [workspace] }
  const manager = new SkillsManager(options)
  const put = async (path: string, raw = text()) => { await fs.mkdir(join(path, '..'), { recursive: true }); await fs.writeFile(path, raw) }
  return { root, dshHome, agentsHome, stateDir, workspace, options, manager, put }
}
const code = (expected: string) => (error: unknown) => (error as { code?: string }).code === expected

