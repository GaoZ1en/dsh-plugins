import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const model = (await readFile(new URL('src/model.js', root), 'utf8')).replace(/^export /gm, '');
const client = (await readFile(new URL('src/client.js', root), 'utf8')).replace(/^export /gm, '');
const palette = (await readFile(new URL('src/palette.js', root), 'utf8')).replace(/^export /gm, '');
const result = `// Generated by scripts/build.mjs. No external runtime imports except React.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n${model}\n${palette}\n${client}\n    return createClient(require('react'), { prepareUserMessage, messageTime, copyOriginal }, { installPalette });\n  }\n});\n`;
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), result);
console.log(`Built ${manifest.name}@${manifest.version}`);
